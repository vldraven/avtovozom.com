def create_and_submit(token: str, article: dict, cover_url: str) -> dict:
    created = req("POST", "/blog/me/posts", token=token, data={"title": ""})
    post_id = created["id"]
    payload = {
        "title": article["title"],
        "excerpt": article["excerpt"],
        "seo_description": article["seo"][:160],
        "section_id": article["section_id"],
        "brand_id": article.get("brand_id"),
        "model_id": article.get("model_id"),
        "cover_url": cover_url,
        "body": article["body"],
        "tags": article["tags"],
        "as_editorial": True,
        "slug": "",
    }
    req("PUT", f"/blog/me/posts/{post_id}", token=token, data=payload)
    submitted = req("POST", f"/blog/me/posts/{post_id}/submit", token=token)
    return submitted


def main() -> None:
    print(f"API={API} email={EMAIL}")
    token = login()
    print("logged in")

    cover_cache: dict[str, str] = {}
    results = []
    for article in ARTICLES:
        cover_name = article["cover"]
        if cover_name not in cover_cache:
            path = COVERS / cover_name
            if not path.exists():
                raise SystemExit(f"missing cover {path}")
            cover_cache[cover_name] = upload(token, path)
            print("uploaded", cover_name, "→", cover_cache[cover_name])
        out = create_and_submit(token, article, cover_cache[cover_name])
        results.append(
            {
                "id": out.get("id"),
                "status": out.get("status"),
                "slug": out.get("slug"),
                "title": out.get("title"),
            }
        )
        print("submitted", out.get("id"), out.get("status"), out.get("slug"))

    pending = req("GET", "/blog/me/posts?status=pending", token=token)
    print("pending_count", len(pending) if isinstance(pending, list) else pending)
    print(json.dumps(results, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
