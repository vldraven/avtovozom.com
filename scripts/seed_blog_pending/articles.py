def P(text: str) -> dict:
    return {"type": "paragraph", "inlines": [{"text": text}]}


def Pm(*parts) -> dict:
    inlines = []
    for part in parts:
        if isinstance(part, str):
            inlines.append({"text": part})
        else:
            inlines.append({"text": part[0], "href": part[1]})
    return {"type": "paragraph", "inlines": inlines}


def H(text: str, level: str = "h2") -> dict:
    return {"type": level, "text": text}


def T(caption: str, rows: list[list[str]]) -> dict:
    return {"type": "table", "caption": caption, "rows": rows}


def req(method: str, path: str, token: str | None = None, data=None, files=None):
    url = f"{API}{path}"
    headers = {}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    body = None
    if files:
        # multipart
        import uuid

        boundary = "----avt" + uuid.uuid4().hex
        headers["Content-Type"] = f"multipart/form-data; boundary={boundary}"
        chunks = []
        for name, (fname, content, ctype) in files.items():
            chunks.append(f"--{boundary}\r\n".encode())
            chunks.append(
                f'Content-Disposition: form-data; name="{name}"; filename="{fname}"\r\n'.encode()
            )
            chunks.append(f"Content-Type: {ctype}\r\n\r\n".encode())
            chunks.append(content)
            chunks.append(b"\r\n")
        chunks.append(f"--{boundary}--\r\n".encode())
        body = b"".join(chunks)
    elif data is not None:
        headers["Content-Type"] = "application/json"
        body = json.dumps(data, ensure_ascii=False).encode("utf-8")
    request = urllib.request.Request(url, data=body, headers=headers, method=method)
    try:
        with urllib.request.urlopen(request, timeout=60) as resp:
            raw = resp.read()
            if not raw:
                return {}
            return json.loads(raw.decode("utf-8"))
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise SystemExit(f"{method} {path} → {exc.code}: {detail[:500]}") from exc


def login() -> str:
    out = req("POST", "/auth/login", data={"email": EMAIL, "password": PASSWORD})
    token = out.get("access_token") or out.get("token")
    if not token:
        raise SystemExit(f"login failed: {out}")
    return token


def upload(token: str, path: Path) -> str:
    data = path.read_bytes()
    ctype = mimetypes.guess_type(path.name)[0] or "image/jpeg"
    out = req(
        "POST",
        "/blog/uploads",
        token=token,
        files={"file": (path.name, data, ctype)},
    )
    url = out.get("url")
    if not url:
        raise SystemExit(f"upload failed: {out}")
    return url


