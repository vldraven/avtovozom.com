function operatorLines() {
  const lines = [`Оператор: ${COMPANY.legalName || COMPANY.brandName}`];
  if (COMPANY.inn) lines.push(`ИНН: ${COMPANY.inn}`);
  if (COMPANY.ogrn) lines.push(`ОГРН: ${COMPANY.ogrn}`);
  if (COMPANY.kpp) lines.push(`КПП: ${COMPANY.kpp}`);
  if (COMPANY.address) lines.push(`Адрес: ${COMPANY.address}`);
  if (COMPANY.phone) lines.push(`Телефон: ${COMPANY.phone}`);
  if (COMPANY.email) lines.push(`Email: ${COMPANY.email}`);
  return lines;
}

